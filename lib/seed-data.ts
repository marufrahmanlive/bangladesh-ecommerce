export const L = (en: string, bn: string): LocalizedText => ({ en, bn });

export const taka = (n: number) => toMinor(n);

interface VarInput {
  id: string;
  sku: string;
  regular: number;
  offer?: number;
  cost: number;
  stock: number;
  low?: number;
  color?: string;
  size?: string;
  barcode?: string;
}

export function mkVar(v: VarInput): ProductVariant {
  return {
    id: v.id,
    sku: v.sku,
    barcode: v.barcode,
    color: v.color,
    size: v.size,
    regularPriceMinor: toMinor(v.regular),
    offerPriceMinor: toMinor(v.offer ?? v.regular),
    costMinor: toMinor(v.cost),
    stock: v.stock,
    lowStockThreshold: v.low ?? 5,
    isActive: true,
  };
}

interface ProductInput {
  id: string;
  nameEn: string;
  nameBn: string;
  slug: string;
  sku: string;
  shortEn: string;
  shortBn: string;
  descEn: string;
  descBn: string;
  categoryId: string;
  brandId?: string;
  supplierId?: string;
  variants: ProductVariant[];
  specs?: Array<{ en: string; bn: string; v: string }>;
  images?: string[];
  weightGrams?: number;
  isFeatured?: boolean;
  isBestSeller?: boolean;
  isNew?: boolean;
}

export function mkProduct(p: ProductInput): Product {
  return {
    id: p.id,
    name: L(p.nameEn, p.nameBn),
    slug: p.slug,
    sku: p.sku,
    shortDescription: L(p.shortEn, p.shortBn),
    description: L(p.descEn, p.descBn),
    specifications: (p.specs ?? []).map((s) => ({
      label: L(s.en, s.bn),
      value: L(s.v, s.v),
    })),
    categoryId: p.categoryId,
    brandId: p.brandId,
    supplierId: p.supplierId,
    images: p.images ?? [`/images/products/${p.slug}.svg`],
    variants: p.variants,
    taxRate: 0,
    weightGrams: p.weightGrams,
    isFeatured: p.isFeatured ?? false,
    isBestSeller: p.isBestSeller ?? false,
    isNew: p.isNew ?? false,
    isPublished: true,
    isArchived: false,
    seoTitle: p.nameEn,
    seoDescription: p.shortEn,
    isSample: true,
    createdAt: FIXED_NOW,
    updatedAt: FIXED_NOW,
  };
}

function mkCat(
  id: string,
  en: string,
  bn: string,
  parentId: string | null,
  order: number,
): Category {
  return {
    id,
    name: L(en, bn),
    slug: slugify(en),
    parentId,
    order,
    isActive: true,
    isSample: true,
    createdAt: FIXED_NOW,
    updatedAt: FIXED_NOW,
  };
}

